function initLevelPagesEvents() {
  const e = document.getElementById("search-course"),
    t = document.getElementById("courses");
  e &&
    t &&
    e.addEventListener("input", () => {
      const n = e.value.toLowerCase().trim(),
        s = t.querySelectorAll(".course-card");
      let o = 0;
      s.forEach((e) => {
        const t = e.querySelector(".course-title").textContent.toLowerCase(),
          s = e.querySelector(".text-muted").textContent.toLowerCase();
        t.includes(n) || s.includes(n)
          ? (e.closest(".col-md-6").classList.remove("d-none"), o++)
          : e.closest(".col-md-6").classList.add("d-none");
      });
      let i = document.getElementById("no-courses-msg");
      0 === o
        ? i ||
          ((i = document.createElement("div")),
          (i.id = "no-courses-msg"),
          (i.className = "col-12 text-center py-5"),
          (i.innerHTML =
            '\n                        <div class="fs-2 text-muted mb-3"><i class="fa-solid fa-book-bookmark"></i></div>\n                        <h5 class="text-muted">لم يتم العثور على مقررات مطابقة للبحث.</h5>\n                    '),
          t.querySelector(".row").appendChild(i))
        : i && i.remove();
    });
  document.querySelectorAll(".course-card").forEach((e) => {
    const t = e.querySelector(".course-title").textContent,
      n = getSlug(t);
    let s = e.querySelector(".favorite-btn");
    s ||
      ((s = document.createElement("button")),
      (s.className = "favorite-btn"),
      (s.innerHTML = '<i class="fa-regular fa-star"></i>'),
      (s.title = "أضف إلى المفضلة"),
      e.appendChild(s));
    (JSON.parse(localStorage.getItem("fav_courses") || "[]").includes(n) &&
      (s.classList.add("is-fav"),
      (s.innerHTML = '<i class="fa-solid fa-star"></i>')),
      s.addEventListener("click", (e) => {
        e.stopPropagation();
        let o = JSON.parse(localStorage.getItem("fav_courses") || "[]");
        (o.includes(n)
          ? ((o = o.filter((e) => e !== n)),
            s.classList.remove("is-fav"),
            (s.innerHTML = '<i class="fa-regular fa-star"></i>'),
            showToast(`تمت إزالة [${t}] من المفضلة`, "info"))
          : (o.push(n),
            s.classList.add("is-fav"),
            (s.innerHTML = '<i class="fa-solid fa-star"></i>'),
            showToast(`تمت إضافة [${t}] إلى المفضلة ⭐`, "success")),
          localStorage.setItem("fav_courses", JSON.stringify(o)));
      }));
    const o = e.querySelector(".d-flex.gap-2");
    if (o) {
      let e = o.querySelector(".complete-toggle-btn");
      if (!e) {
        ((e = document.createElement("button")),
          (e.className = "complete-toggle-btn btn-sm btn"),
          (e.innerHTML =
            '<i class="fa-regular fa-circle-check"></i> غير مكتمل'));
        ("true" === localStorage.getItem(`complete_${n}`) &&
          (e.classList.add("is-complete"),
          (e.innerHTML = '<i class="fa-solid fa-circle-check"></i> مكتمل')),
          e.addEventListener("click", (s) => {
            s.preventDefault();
            "true" === localStorage.getItem(`complete_${n}`)
              ? (localStorage.setItem(`complete_${n}`, "false"),
                e.classList.remove("is-complete"),
                (e.innerHTML =
                  '<i class="fa-regular fa-circle-check"></i> غير مكتمل'),
                showToast(`تم تعيين [${t}] كغير مكتمل`, "info"))
              : (localStorage.setItem(`complete_${n}`, "true"),
                e.classList.add("is-complete"),
                (e.innerHTML =
                  '<i class="fa-solid fa-circle-check"></i> مكتمل'),
                showToast(`رائع! أكملت دراسة مقرر [${t}] ✔️`, "success"));
          }),
          o.appendChild(e));
      }
    }
  });
}
function getSlug(e) {
  return e
    .trim()
    .toLowerCase()
    .replace(/[\s]+/g, "-")
    .replace(/[^\w\u0600-\u06FF-]/g, "");
}
