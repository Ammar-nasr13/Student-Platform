// إخفاء شاشة التحميل المسبق
function hidePreloader() {
    const preloader = document.getElementById('preloader');
    if (preloader) {
        preloader.classList.add('fade-out');
        setTimeout(() => {
            preloader.style.display = 'none';
        }, 500);
    }
}

// تفعيل روابط الهيدر النشطة
function highlightActiveNavLink() {
    const currentPath = window.location.pathname.split('/').pop();
    const navLinks = document.querySelectorAll('.navbar-nav .nav-link');
    navLinks.forEach(link => {
        const linkPath = link.getAttribute('href');
        if (currentPath === linkPath) {
            link.classList.add('active');
        } else {
            link.classList.remove('active');
        }
    });
}

/* ==========================================================================
   نظام تبديل المظهر (Dark / Light Mode Toggle)
   ========================================================================== */

function initThemeMode() {
    const themeBtn = document.getElementById('theme-toggle');
    if (!themeBtn) return;

    // قراءة المظهر المخزن مسبقاً
    const currentTheme = localStorage.getItem('theme') || 'light';
    
    if (currentTheme === 'dark') {
        document.body.classList.add('dark-theme');
        themeBtn.innerHTML = '<i class="fa-solid fa-sun text-warning"></i>'; // رمز الشمس للعودة للفاتح
    } else {
        document.body.classList.remove('dark-theme');
        themeBtn.innerHTML = '<i class="fa-solid fa-moon"></i>'; // رمز القمر للمظلم
    }

    themeBtn.addEventListener('click', () => {
        document.body.classList.toggle('dark-theme');
        
        let theme = 'light';
        if (document.body.classList.contains('dark-theme')) {
            theme = 'dark';
            themeBtn.innerHTML = '<i class="fa-solid fa-sun text-warning"></i>';
            showToast("تم تفعيل الوضع الليلي 🌙", "info");
        } else {
            themeBtn.innerHTML = '<i class="fa-solid fa-moon"></i>';
            showToast("تم تفعيل الوضع المضيء ☀️", "info");
        }
        localStorage.setItem('theme', theme);
    });
}

/* ==========================================================================
   زر العودة للأعلى (Back to Top UX)
   ========================================================================== */

function initBackToTop() {
    // إنشاء الزر ديناميكياً إذا لم يكن موجوداً
    let btn = document.getElementById('back-to-top-btn');
    if (!btn) {
        btn = document.createElement('button');
        btn.id = 'back-to-top-btn';
        btn.className = 'back-to-top';
        btn.innerHTML = '<i class="fa-solid fa-arrow-up"></i>';
        document.body.appendChild(btn);
    }

    // إظهار وإخفاء الزر عند التمرير
    window.addEventListener('scroll', () => {
        if (window.scrollY > 300) {
            btn.classList.add('show');
        } else {
            btn.classList.remove('show');
        }
    });

    // العودة بسلاسة عند الضغط
    btn.addEventListener('click', () => {
        window.scrollTo({
            top: 0,
            behavior: 'smooth'
        });
    });
}

/* ==========================================================================
   نظام التنبيهات المخصصة المنبثقة (Toast Notifications UX)
   ========================================================================== */

function showToast(message, type = 'success') {
    // التحقق من وجود الحاوية أو إنشاؤها
    let container = document.getElementById('toast-container');
    if (!container) {
        container = document.createElement('div');
        container.id = 'toast-container';
        document.body.appendChild(container);
    }

    // إنشاء التنبيه
    const toast = document.createElement('div');
    toast.className = `custom-toast toast-${type}`;
    
    let icon = '<i class="fa-solid fa-circle-check text-success"></i>';
    if (type === 'info') icon = '<i class="fa-solid fa-circle-info text-info"></i>';
    if (type === 'warning') icon = '<i class="fa-solid fa-triangle-exclamation text-warning"></i>';

    toast.innerHTML = `
        ${icon}
        <div>${message}</div>
    `;

    container.appendChild(toast);

    // إزالة التنبيه بعد 3.5 ثانية
    setTimeout(() => {
        toast.style.opacity = '0';
        setTimeout(() => {
            toast.remove();
        }, 300);
    }, 3500);
}

/* ==========================================================================
   تحديثات صفحات المستويات الدراسية (البحث، المفضلة، الاكتمال، تفاصيل المقرر)
   ========================================================================== */

function initLevelPagesEvents() {
    const courseSearch = document.getElementById('search-course');
    const coursesContainer = document.getElementById('courses');
    
    // 1. ميزة البحث الفوري عن المقررات داخل المستوى
    if (courseSearch && coursesContainer) {
        courseSearch.addEventListener('input', () => {
            const query = courseSearch.value.toLowerCase().trim();
            const cards = coursesContainer.querySelectorAll('.course-card');
            let foundCount = 0;

            cards.forEach(card => {
                const title = card.querySelector('.course-title').textContent.toLowerCase();
                const desc = card.querySelector('.text-muted').textContent.toLowerCase();

                if (title.includes(query) || desc.includes(query)) {
                    card.closest('.col-md-6').classList.remove('d-none');
                    foundCount++;
                } else {
                    card.closest('.col-md-6').classList.add('d-none');
                }
            });

            // إظهار رسالة عدم وجود مواد
            let noResultMsg = document.getElementById('no-courses-msg');
            if (foundCount === 0) {
                if (!noResultMsg) {
                    noResultMsg = document.createElement('div');
                    noResultMsg.id = 'no-courses-msg';
                    noResultMsg.className = 'col-12 text-center py-5';
                    noResultMsg.innerHTML = `
                        <div class="fs-2 text-muted mb-3"><i class="fa-solid fa-book-bookmark"></i></div>
                        <h5 class="text-muted">لم يتم العثور على مقررات مطابقة للبحث.</h5>
                    `;
                    coursesContainer.querySelector('.row').appendChild(noResultMsg);
                }
            } else {
                if (noResultMsg) noResultMsg.remove();
            }
        });
    }

    // 2. تفعيل أزرار النجمة والمفضلة والاكتمال لبطاقات المواد
    const cards = document.querySelectorAll('.course-card');
    cards.forEach(card => {
        // تحديد معرّف فريد للمادة بناء على اسمها أو رابطها
        const titleText = card.querySelector('.course-title').textContent;
        const courseId = getSlug(titleText);

        // إدراج النجمة ديناميكياً في البطاقة
        let favBtn = card.querySelector('.favorite-btn');
        if (!favBtn) {
            favBtn = document.createElement('button');
            favBtn.className = 'favorite-btn';
            favBtn.innerHTML = '<i class="fa-regular fa-star"></i>';
            favBtn.title = "أضف إلى المفضلة";
            card.appendChild(favBtn);
        }

        // قراءة حالة المفضلة المخزنة
        const favorites = JSON.parse(localStorage.getItem('fav_courses') || '[]');
        if (favorites.includes(courseId)) {
            favBtn.classList.add('is-fav');
            favBtn.innerHTML = '<i class="fa-solid fa-star"></i>';
        }

        // حدث الضغط على النجمة
        favBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            let favs = JSON.parse(localStorage.getItem('fav_courses') || '[]');
            if (favs.includes(courseId)) {
                favs = favs.filter(id => id !== courseId);
                favBtn.classList.remove('is-fav');
                favBtn.innerHTML = '<i class="fa-regular fa-star"></i>';
                showToast(`تمت إزالة [${titleText}] من المفضلة`, "info");
            } else {
                favs.push(courseId);
                favBtn.classList.add('is-fav');
                favBtn.innerHTML = '<i class="fa-solid fa-star"></i>';
                showToast(`تمت إضافة [${titleText}] إلى المفضلة ⭐`, "success");
            }
            localStorage.setItem('fav_courses', JSON.stringify(favs));
        });

        // إدراج زر "تحديد كـ مكتمل" بجوار التحميل
        const actionsDiv = card.querySelector('.d-flex.gap-2');
        if (actionsDiv) {
            let completeBtn = actionsDiv.querySelector('.complete-toggle-btn');
            if (!completeBtn) {
                completeBtn = document.createElement('button');
                completeBtn.className = 'complete-toggle-btn btn-sm btn';
                completeBtn.innerHTML = '<i class="fa-regular fa-circle-check"></i> غير مكتمل';
                
                // قراءة حالة الاكتمال المخزنة
                const isComplete = localStorage.getItem(`complete_${courseId}`) === 'true';
                if (isComplete) {
                    completeBtn.classList.add('is-complete');
                    completeBtn.innerHTML = '<i class="fa-solid fa-circle-check"></i> مكتمل';
                }

                // حدث الضغط على اكتمال المادة
                completeBtn.addEventListener('click', (e) => {
                    e.preventDefault();
                    const currentState = localStorage.getItem(`complete_${courseId}`) === 'true';
                    if (currentState) {
                        localStorage.setItem(`complete_${courseId}`, 'false');
                        completeBtn.classList.remove('is-complete');
                        completeBtn.innerHTML = '<i class="fa-regular fa-circle-check"></i> غير مكتمل';
                        showToast(`تم تعيين [${titleText}] كغير مكتمل`, "info");
                    } else {
                        localStorage.setItem(`complete_${courseId}`, 'true');
                        completeBtn.classList.add('is-complete');
                        completeBtn.innerHTML = '<i class="fa-solid fa-circle-check"></i> مكتمل';
                        showToast(`رائع! أكملت دراسة مقرر [${titleText}] ✔️`, "success");
                    }
                });

                // وضعه كأول زر أو دمجه مع الأزرار
                actionsDiv.appendChild(completeBtn);
            }

        }
    });
}

// دالة لتحويل العنوان إلى معرّف قصير
function getSlug(text) {
    return text.trim().toLowerCase()
        .replace(/[\s]+/g, '-')
        .replace(/[^\w\u0600-\u06FF-]/g, '');
}

