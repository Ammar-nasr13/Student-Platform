document.addEventListener('DOMContentLoaded', () => {
    checkAuthSession();
});

function checkAuthSession() {
    const gateway = document.getElementById('auth-gateway');
    
    // We only update the UI for faculty, but we DO NOT auto-hide the gateway anymore.
    // The user requested the selection screen to always appear first.
    updateUIForFaculty();
}

window.selectRole = function(role) {
    if (role === 'student') {
        // If they choose student, make sure they are completely logged out of faculty role
        localStorage.removeItem('is_faculty');
        const navAddExam = document.getElementById('nav-add-exam');
        if (navAddExam) navAddExam.remove();
        
        closeAuthGateway();
    } else if (role === 'faculty') {
        // If already logged in as faculty, skip the password screen and just enter
        if (localStorage.getItem('is_faculty') === 'true') {
            closeAuthGateway();
            updateUIForFaculty();
        } else {
            document.getElementById('auth-role-selection').classList.add('d-none');
            document.getElementById('auth-faculty-login').classList.remove('d-none');
        }
    }
};

window.logoutFaculty = async function() {
    try {
        if (window.AppwriteAccount) {
            await window.AppwriteAccount.deleteSession('current');
        }
    } catch(err) {
        console.error("Logout error:", err);
    }
    localStorage.removeItem('is_faculty');
    // Remove UI button and show gateway
    const navAddExam = document.getElementById('nav-add-exam');
    if (navAddExam) navAddExam.remove();
    
    // Show gateway if on index
    const gateway = document.getElementById('auth-gateway');
    if (gateway) {
        gateway.classList.remove('d-none', 'fade-out');
        document.getElementById('auth-role-selection').classList.remove('d-none');
        document.getElementById('auth-faculty-login').classList.add('d-none');
    } else {
        window.location.href = 'index.html';
    }
};

window.backToRoles = function() {
    document.getElementById('auth-role-selection').classList.remove('d-none');
    document.getElementById('auth-faculty-login').classList.add('d-none');
    document.getElementById('auth-error').classList.add('d-none');
};

window.loginFaculty = async function() {
    const user = document.getElementById('faculty-username').value;
    const pass = document.getElementById('faculty-password').value;
    const errorEl = document.getElementById('auth-error');
    
    const btns = document.querySelectorAll('#auth-faculty-login button');
    let loginBtn = null;
    btns.forEach(b => { if (b.textContent.includes('تسجيل')) loginBtn = b; });
    
    let originalText = 'تسجيل الدخول';
    if (loginBtn) {
        originalText = loginBtn.innerHTML;
        loginBtn.innerHTML = '<i class="fa-solid fa-spinner fa-spin me-2"></i> جاري التحقق...';
        loginBtn.disabled = true;
    }

    try {
        await window.AppwriteAccount.createEmailPasswordSession(user, pass);
        
        localStorage.setItem('is_faculty', 'true');
        errorEl.classList.add('d-none');
        closeAuthGateway();
        updateUIForFaculty();
        
    } catch (err) {
        console.error('Auth Error:', err);
        const errStr = String(err).toLowerCase();
        
        if (errStr.includes('fetch') || errStr.includes('network')) {
            errorEl.innerHTML = '<i class="fa-solid fa-wifi me-1 mb-1 fs-5"></i><br><b>تعذر الاتصال بالخادم</b><br><small>يرجى التحقق من اتصالك بالإنترنت والمحاولة مرة أخرى.</small>';
        } else if (errStr.includes('session')) {
            errorEl.innerHTML = '<i class="fa-solid fa-circle-check me-1 mb-1 fs-6"></i><br>أنت مسجل الدخول بالفعل، جاري توجيهك...';
            setTimeout(() => {
                localStorage.setItem('is_faculty', 'true');
                errorEl.classList.add('d-none');
                closeAuthGateway();
                updateUIForFaculty();
            }, 1500);
            return;
        } else {
            errorEl.innerHTML = '<i class="fa-solid fa-circle-xmark me-1 mb-1 fs-6"></i><br>البريد الإلكتروني أو كلمة المرور غير صحيحة.';
        }
        
        errorEl.classList.remove('d-none');
    } finally {
        if (loginBtn) {
            loginBtn.innerHTML = originalText;
            loginBtn.disabled = false;
        }
    }
};

function closeAuthGateway() {
    const gateway = document.getElementById('auth-gateway');
    if (gateway) {
        gateway.classList.add('fade-out');
        setTimeout(() => {
            gateway.classList.add('d-none');
        }, 400); // Wait for transition
    }
}

function updateUIForFaculty() {
    const isFaculty = localStorage.getItem('is_faculty');
    if (isFaculty === 'true') {
        // إضافة زر (إضافة اختبار) في الناف بار إذا كان موجوداً
        const navUl = document.querySelector('.navbar-nav');
        if (navUl && !document.getElementById('nav-add-exam')) {
            const li = document.createElement('li');
            li.className = 'nav-item ms-lg-3 mt-3 mt-lg-0';
            li.id = 'nav-add-exam';
            li.innerHTML = '<a href="add_exam.html" class="btn btn-warning fw-bold px-3 rounded-pill text-dark shadow-sm"><i class="fa-solid fa-plus-circle me-1"></i> إضافة اختبار</a>';
            navUl.appendChild(li);
        }
    }
}
